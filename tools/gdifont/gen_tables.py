#!/usr/bin/env python3
"""Generate render/gdifont_tables.inc: the GDI BITMAP-font metrics stock DreamSeeker lays maptext out with.

DreamSeeker measures (and draws) maptext through GDI: CreateFont(lfHeight = -em) + GetTextMetrics + the per-character
advance widths (see render/dsmaptext.h). For the bitmap faces it resolves - 'Small Fonts', 'MS Sans
Serif' (its default face) and 'Courier' (monospace) - those numbers are simply the .FON file's FNT header and width
table, so this script reads them straight out of the font files, no rasteriser involved.

Source: the font files Wine 9.0 resolves for those families (gdimetrics.c prints the face GDI picks for each family):

    /usr/share/wine/fonts/smalle.fon   md5 c41447c91f1e2dc3575ee67acea73b22   (Small Fonts: ONE strike, 7pt)
    /usr/share/wine/fonts/sserife.fon  md5 159d172e900cfb52533638685a121bd1   (MS Sans Serif 8/10/12pt)
    /usr/share/wine/fonts/coure.fon    md5 fa541bfc84bca578cd4fdaaf1f4fbc11   (Courier 10pt)

Only the 96-dpi strikes are emitted. Usage: gen_tables.py [fontdir] > render/gdifont_tables.inc
"""
import struct
import sys

FONTDIR = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/wine/fonts'
FILES = [('smalle.fon', 'kFaceSmallFonts'), ('sserife.fon', 'kFaceMsSansSerif'), ('coure.fon', 'kFaceCourier')]


def strikes(path):
    d = open(path, 'rb').read()
    ne = struct.unpack_from('<H', d, 0x3c)[0]
    rt = ne + struct.unpack_from('<H', d, ne + 0x24)[0]
    shift = struct.unpack_from('<H', d, rt)[0]
    p = rt + 2
    out = []
    while True:
        t = struct.unpack_from('<H', d, p)[0]
        if t == 0:
            break
        n = struct.unpack_from('<H', d, p + 2)[0]
        p += 8
        for _ in range(n):
            off = struct.unpack_from('<H', d, p)[0]
            p += 12
            if t != 0x8008:   # RT_FONT
                continue
            f = off << shift
            ver = struct.unpack_from('<H', d, f)[0]
            pts, vres, hres, asc, il, el = struct.unpack_from('<HHHHHH', d, f + 0x44)
            pixh = struct.unpack_from('<H', d, f + 0x58)[0]
            first, last, default = d[f + 0x5f], d[f + 0x60], d[f + 0x61]
            if hres != 96 or vres != 96:
                continue
            hdr, step = (0x76, 4) if ver == 0x200 else (0x94, 6)
            adv = [struct.unpack_from('<H', d, f + hdr + (c - first) * step)[0] for c in range(first, last + 1)]
            out.append(dict(pt=pts, h=pixh, ascent=asc, il=il, first=first, default=default + first, adv=adv))
    return out


HEADER = [
    "// GENERATED by tools/gdifont/gen_tables.py from wine 9.0's bitmap fonts - do not edit by hand.",
    "// SOURCE: the advance widths and strike metrics below are read from wine 9.0's bitmap font files smalle.fon (Small",
    "// Fonts), sserife.fon (MS Sans Serif) and coure.fon (Courier), as shipped by Debian/Ubuntu's fonts-wine package",
    "// (/usr/share/wine/fonts). Only the numbers are taken, no glyph bitmaps.",
    '// {pt, tmHeight, tmAscent, tmInternalLeading, firstChar, defaultChar, advances[firstChar..255]} per 96-dpi strike.',
]
for h in HEADER:
    print(h)
for fname, sym in FILES:
    for s in strikes(FONTDIR + '/' + fname):
        assert s['first'] == 32 and len(s['adv']) == 224, (fname, s['first'], len(s['adv']))
        print('static const GdiStrike %s_%d = {%d, %d, %d, %d, %d, %d, {' % (sym, s['pt'], s['pt'], s['h'], s['ascent'], s['il'],
                                                                     s['first'], s['default']))
        a = s['adv']
        for i in range(0, len(a), 32):
            print('    ' + ', '.join('%d' % x for x in a[i:i + 32]) + ',')
        print('}};')
